"""문형 뱅크 — 요일별 카테고리, N3 이상.

동사 활용표 방식은 폐기했다. 여기 들어가는 항목은 전부 "구조로 기능하는
문형"이며, 사전 하나로 해결되는 단어 나열이 아니다 (부사도 예외 없이
구문 세트로만 등록한다: せっかく〜のに, 단독 せっかく는 넣지 않는다).

외부 사이트를 스크래핑해서 채우지 않는다. JLPTsensei 등 학습 사이트의
문형 목록은 그 자체가 저작물이라, 개수·분류 체계만 참고하고 실제 항목은
직접 검증해서 하나씩 넣는다. 그래서 카테고리별 개수가 균일하지 않고,
운영하면서 실제 지문에 넣어본 것만 점진적으로 늘어난다.

각 항목은 (id, terms) 형태다.
- id: 화면에 표시되지 않는 내부 식별자. 로그와 쿨다운 이력에만 쓰인다.
- terms: 지문에 이 문형이 실제로 들어갔는지 검증할 때 찾을 부분 문자열.
  [[a, b], [c]] 형태는 "(a와 b가 모두 있다) 또는 (c가 있다)"를 뜻한다.
  파서가 id에서 자동으로 뽑아내므로 보통 별도로 안 써도 된다 (parse_terms 참고).
"""

import re

# ── id 문자열에서 검증용 부분 문자열을 자동으로 뽑아내는 파서 ──────────
def parse_terms(pattern_id: str):
    """
    'せっかく〜のに'      -> [['せっかく', 'のに']]
    'にしても/にしろ/にせよ' -> [['にしても'], ['にしろ'], ['にせよ']]
    'そうだ(伝聞)'         -> [['そうだ']]   (괄호 설명은 검증에서 제외)
    'たる(者)'            -> [['たる']]
    """
    # 괄호 설명 제거 (そうだ(伝聞) → そうだ)
    cleaned = re.sub(r"[（(].*?[）)]", "", pattern_id)
    alts = cleaned.split("/") if "/" in cleaned else [cleaned]
    groups = []
    for alt in alts:
        parts = [p for p in alt.split("〜") if p]
        if parts:
            groups.append(parts)
    return groups or [[cleaned]]


class Pattern:
    __slots__ = ("id", "terms", "note")

    def __init__(self, pattern_id: str, note: str = None):
        self.id = pattern_id
        self.terms = parse_terms(pattern_id)
        # note: 결합 제약이 좁거나(콜로케이션), 뒷문장과 짝을 이뤄야 완성되는
        # 문형에 한해 프롬프트에 그대로 전달할 사용 지침. 89개 전수 점검에서
        # 결합 범위가 넓은 문형은 note 없이 그대로 둔다.
        self.note = note

    def found_in(self, text: str) -> bool:
        return any(all(t in text for t in group) for group in self.terms)


def _bank(*items):
    out = []
    for it in items:
        if isinstance(it, tuple):
            out.append(Pattern(it[0], it[1]))
        else:
            out.append(Pattern(it))
    return out


